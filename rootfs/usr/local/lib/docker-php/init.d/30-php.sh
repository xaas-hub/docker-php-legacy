# shellcheck shell=bash
#
# Generates /run/docker-php/php.ini, loaded last through a link in conf.d:
#
# - PHP_EXTENSIONS: optional extensions to enable, from $PHP_INI_DIR/available
# - APP_ENV: outside production, .user-<APP_ENV>.ini replaces .user.ini, read
#   on every request
# - PHP_INI_<NAME>: any php.ini directive, written last so it wins

# Extensions the optional ones were compiled against: they refuse to load
# without them.
declare -A PHP_EXTENSION_DEPS=(
	[memcached]="igbinary msgpack"
	[redis]="igbinary msgpack"
)

# Prints the ini files of the requested extensions and their dependencies, in
# load order. Call it through a command substitution checked by set -e: die
# only leaves the subshell.
php_extension_ini_files() {
	local ext dep available
	local -A wanted=()
	local -a ini files=()

	# shellcheck disable=SC2013 # word splitting is the point
	for ext in $(tr ',;' ' ' <<<"${PHP_EXTENSIONS,,}"); do
		wanted[$ext]=1
		for dep in ${PHP_EXTENSION_DEPS[$ext]:-}; do
			wanted[$dep]=1
		done
	done

	for ext in "${!wanted[@]}"; do
		ini=("${PHP_INI_DIR}/available/"*-php-ext-"${ext}".ini)
		if [ -f "${ini[0]}" ]; then
			files+=("${ini[0]}")
		elif [ -n "$(find "${PHP_INI_DIR}/conf.d" -name "*-php-ext-${ext}.ini" -print -quit)" ]; then
			log "PHP_EXTENSIONS: ${ext} is always enabled"
		else
			available="$(cd "${PHP_INI_DIR}/available" && printf '%s\n' *.ini | sed -E 's/^.*-php-ext-(.*)\.ini$/\1/' | sort | paste -sd ' ')"
			die "PHP_EXTENSIONS: ${ext} is not available. Optional extensions: ${available}." \
				"Any other one needs an image built FROM this one with: RUN install-php-extensions ${ext}"
		fi
	done

	# The file names carry the load order chosen by install-php-extensions
	# (docker-php-ext-igbinary before docker-php-ext-redis, xx-php-ext-memcached
	# after both serializers).
	if [ "${#files[@]}" -gt 0 ]; then
		printf '%s\n' "${files[@]}" | awk -F/ '{ print $NF "\t" $0 }' | sort | cut -f2-
	fi
}

php_runtime_ini() {
	local app_env="${APP_ENV:-production}" ext_inis ini

	[[ "$app_env" =~ ^[A-Za-z0-9._-]+$ ]] ||
		die "APP_ENV may only contain letters, digits, dots, dashes and underscores"

	echo "; Generated by docker-php-init at every start: changes are lost."
	echo

	if [ -n "${PHP_EXTENSIONS:-}" ]; then
		ext_inis="$(php_extension_ini_files)"
		echo "; PHP_EXTENSIONS=${PHP_EXTENSIONS}"
		while IFS= read -r ini; do
			[ -n "$ini" ] || continue
			cat "$ini"
			echo
		done <<<"$ext_inis"
	fi

	if [ "$app_env" != production ]; then
		echo "; APP_ENV=${app_env}"
		echo "user_ini.filename = \".user-${app_env}.ini\""
		echo "user_ini.cache_ttl = 0"
		echo
	fi

	echo "; PHP_INI_*"
	env_to_ini PHP_INI_ PHP_INI_DIR PHP_INI_SCAN_DIR
}

# Built in full before anything is written: a failure leaves the previous file
# in place instead of a truncated one.
php_runtime_ini_content="$(php_runtime_ini)"
printf '%s\n' "$php_runtime_ini_content" | write_file "${DOCKER_PHP_RUNTIME_DIR}/php.ini" 0644
unset php_runtime_ini_content

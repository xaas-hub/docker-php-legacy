# shellcheck shell=bash
#
# FPM_POOL_<NAME>: any directive of the www pool, same naming as PHP_INI_*
# (FPM_POOL_PM__MAX_CHILDREN=20 -> pm.max_children = "20"). Written to
# /run/docker-php/fpm.d/, which php-fpm.conf includes after every other file.

if command -v php-fpm >/dev/null; then
	fpm_pool_content="$(
		echo "; Generated by docker-php-init at every start: changes are lost."
		echo "[www]"
		env_to_ini FPM_POOL_
	)"
	# Already there in the image, but not on a tmpfs mounted over the
	# runtime directory (read-only rootless containers).
	mkdir -p "${DOCKER_PHP_RUNTIME_DIR}/fpm.d"
	printf '%s\n' "$fpm_pool_content" | write_file "${DOCKER_PHP_RUNTIME_DIR}/fpm.d/zz-runtime.conf" 0644
	unset fpm_pool_content
fi

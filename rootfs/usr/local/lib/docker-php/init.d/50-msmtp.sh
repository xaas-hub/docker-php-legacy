# shellcheck shell=bash
#
# MSMTP_*: generates the msmtp configuration that PHP's mail() uses through
# sendmail_path. Without MSMTP_HOST nothing is written, and a file mounted on
# /etc/msmtprc (or ~/.msmtprc of www-data) is used as it is.
#
# /etc/msmtprc is the system configuration, so msmtp does not insist on it
# being private to the calling user: it is readable by www-data and root only.

# Quotes a value for msmtprc, where a double-quoted argument may contain spaces
# and backslash-escaped quotes and backslashes.
msmtp_quote() {
	local value="$1"
	value="${value//\\/\\\\}"
	value="${value//\"/\\\"}"
	printf '"%s"' "$value"
}

msmtp_config() {
	local port tls password=""

	port="${MSMTP_PORT:-587}"
	[[ "$port" =~ ^[0-9]+$ ]] || die "MSMTP_PORT must be numeric, got '${port}'"

	# Port 465 speaks TLS from the first byte; anything else is assumed to
	# upgrade with STARTTLS unless told otherwise.
	tls="${MSMTP_TLS:-}"
	if [ -z "$tls" ]; then
		if [ "$port" = 465 ]; then tls=on; else tls=starttls; fi
	fi

	if [ -n "${MSMTP_PASSWORD_FILE:-}" ]; then
		[ -r "${MSMTP_PASSWORD_FILE}" ] || die "MSMTP_PASSWORD_FILE: cannot read ${MSMTP_PASSWORD_FILE}"
		password="$(<"${MSMTP_PASSWORD_FILE}")"
	elif [ -n "${MSMTP_PASSWORD:-}" ]; then
		password="${MSMTP_PASSWORD}"
	fi

	echo "# Generated by docker-php-init at every start: changes are lost."
	echo "defaults"
	case "${tls,,}" in
	starttls)
		echo "tls on"
		echo "tls_starttls on"
		;;
	on)
		echo "tls on"
		echo "tls_starttls off"
		;;
	off)
		echo "tls off"
		;;
	*) die "MSMTP_TLS must be starttls, on or off, got '${tls}'" ;;
	esac
	if [ "${tls,,}" != off ]; then
		echo "tls_trust_file /etc/ssl/certs/ca-certificates.crt"
		if is_true "${MSMTP_TLS_CERTCHECK:-on}"; then
			echo "tls_certcheck on"
		else
			echo "tls_certcheck off"
		fi
	fi
	if [ -n "${MSMTP_LOGFILE:-}" ]; then
		echo "logfile $(msmtp_quote "${MSMTP_LOGFILE}")"
	fi
	echo
	echo "account default"
	echo "host $(msmtp_quote "${MSMTP_HOST}")"
	echo "port ${port}"
	if [ -n "${MSMTP_FROM:-}" ]; then
		echo "from $(msmtp_quote "${MSMTP_FROM}")"
	fi
	if [ -n "${MSMTP_USER:-}" ]; then
		echo "auth on"
		echo "user $(msmtp_quote "${MSMTP_USER}")"
		if [ -n "$password" ]; then
			echo "password $(msmtp_quote "$password")"
		fi
	else
		echo "auth off"
	fi
}

if [ -n "${MSMTP_HOST:-}" ]; then
	msmtp_content="$(msmtp_config)"
	printf '%s\n' "$msmtp_content" | write_file "${DOCKER_PHP_RUNTIME_DIR}/msmtprc" 0640 "$DOCKER_PHP_APP_USER"
	unset msmtp_content
fi

# The password is in the configuration by now. Nothing started from here on
# (Supercronic, hooks, PHP itself) has a reason to see it, and with
# clear_env = no every FPM worker would.
unset MSMTP_PASSWORD
